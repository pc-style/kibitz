// Copies the bundled piece sets from a lichess (lila) checkout into public/pieces and writes
// src/pieces.css. Run once when the sets change: node scripts/copy-pieces.mjs ~/src/lila
// Only sets whose licenses allow redistribution in a GPL project (see public/pieces/LICENSES.md).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const lila = process.argv[2];
if (!lila) throw new Error('usage: node scripts/copy-pieces.mjs <path to lila checkout>');

export const SETS = ['cburnett', 'merida', 'chessnut', 'fantasy', 'spatial', 'celtic'];
const ROLES = { P: 'pawn', N: 'knight', B: 'bishop', R: 'rook', Q: 'queen', K: 'king' };
const COLORS = { w: 'white', b: 'black' };

let css = '/* Generated by scripts/copy-pieces.mjs. cburnett is chessground\'s built-in set, so it needs no rules. */\n';
for (const set of SETS) {
  const to = new URL(`../public/pieces/${set}/`, import.meta.url);
  mkdirSync(to, { recursive: true });
  for (const [c, color] of Object.entries(COLORS)) {
    for (const [r, role] of Object.entries(ROLES)) {
      copyFileSync(join(lila, 'public/piece', set, `${c}${r}.svg`), new URL(`${c}${r}.svg`, to));
      if (set !== 'cburnett') css += `[data-pieces='${set}'] .cg-wrap piece.${role}.${color} { background-image: url('/pieces/${set}/${c}${r}.svg'); }\n`;
    }
  }
}
writeFileSync(new URL('../src/pieces.css', import.meta.url), css);
console.log(`copied ${SETS.length} sets`);
